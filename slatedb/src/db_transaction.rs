/// The reads of a transaction that its commit checks for read-write conflicts: keys
/// that a Serializable transaction read or that `mark_read` marked, and the ranges
/// that `mark_read_range` marked or that its scans read, taken at commit. Each key
/// and each range carries the mask of the conflict domains that its reads used (see
/// [`DbTransaction::mark_read_masked`]).
#[derive(Default)]
pub(crate) struct ReadSet {
    pub(crate) keys: HashMap<Bytes, u64>,
    pub(crate) ranges: Vec<(BytesRange, u64)>,
}

impl ReadSet {
    /// Records a read of `key` that used the conflict domains of `mask`, joined with the
    /// domains of the key's earlier reads. A mask of 0 records nothing.
    pub(crate) fn mark(&mut self, key: Bytes, mask: u64) {
        if mask != 0 {
            *self.keys.entry(key).or_insert(0) |= mask;
        }
    }
}

/// How the commit tracks a transaction's writes for conflict detection.
#[derive(Default)]
struct WriteTracking {
    /// Keys that should be excluded from write conflict detection when committing.
    untracked: HashSet<Bytes>,
    /// The conflict domains that the transaction's writes of a key change, by key, from
    /// `set_write_mask`. A written key that is not here changes every domain.
    masks: HashMap<Bytes, u64>,
    /// The sequence numbers from `validate_write_since`, by key.
    since: HashMap<Bytes, u64>,
}

/// A database transaction that provides atomic read-write operations with
/// configurable isolation levels. This is the main interface for transactional
/// operations in SlateDB.
///
/// Committing a non-empty transaction returns a [`WriteHandle`] without
/// waiting for durability. Call [`WriteHandle::await_durable`] on that handle
/// to wait for that commit, or call [`crate::Db::flush`] to flush all pending
/// writes.
///
/// # Examples
///
/// Basic transaction usage:
/// ```rust
/// # async fn run() -> Result<(), slatedb::Error> {
/// #     use std::sync::Arc;
/// #     use slatedb::object_store::memory::InMemory;
/// use slatedb::{Db, IsolationLevel};
///
/// #     let object_store = Arc::new(InMemory::new());
/// #     let db = Db::open("path/to/db", object_store).await?;
/// let txn = db.begin(IsolationLevel::Snapshot)?;
///
/// // Read operations
/// let value = txn.get(b"key").await?;
///
/// // Write operations
/// txn.put(b"key", b"value")?;
/// txn.delete(b"key")?;
///
/// // Commit the transaction
/// txn.commit().await?;
/// # Ok(())
/// # };
/// ```
pub struct DbTransaction {
    /// Transaction ID generated by the transaction manager
    txn_id: Uuid,
    /// Sequence number when the transaction started
    started_seq: u64,
    /// Reference to the transaction manager
    txn_manager: Arc<TransactionManager>,
    /// The write batch of the transaction, which contains the uncommitted writes.
    /// Users can read data from the write batch during the transaction, thus providing
    /// an MVCC view of the database.
    ///
    /// DbTransaction is not intended for concurrent use; we use `RwLock` (not `RefCell`) for
    /// interior mutability to preserve `Sync` in async contexts. `RefCell` is `!Sync` and would
    /// make `DbTransaction` `!Sync`, which is incompatible with async code using the `DbReadOps`
    /// trait.
    write_batch: RwLock<WriteBatch>,
    /// Reference to the database
    db_inner: Arc<DbInner>,
    /// Isolation level for this transaction
    isolation_level: IsolationLevel,
    /// Range trackers for scanned ranges (used for SSI conflict detection), each with the
    /// mask of the conflict domains that its scan used
    range_trackers: Mutex<Vec<(DbIteratorRangeTracker, u64)>>,
    /// The reads that the commit checks for read-write conflicts. Only this
    /// transaction's commit reads them, so they stay here and not in the shared
    /// transaction manager.
    read_set: Mutex<ReadSet>,
    /// Keys that should be excluded from write conflict detection when committing, and the
    /// conflict domains that the writes of the others change.
    write_tracking: RwLock<WriteTracking>,
    /// The retention of the transaction's sequence number, which the iterators of its scans
    /// hold too, so that it outlives the transaction while one of them reads on. `None` only
    /// while the transaction drops.
    retention: Option<Arc<RetentionPin>>,
}

impl DbTransaction {
    #[allow(unused)]
    pub(crate) fn new(
        db_inner: Arc<DbInner>,
        txn_manager: Arc<TransactionManager>,
        isolation_level: IsolationLevel,
    ) -> Self {
        let (txn_id, seq) = txn_manager.new_transaction();

        Self {
            txn_id,
            started_seq: seq,
            retention: Some(RetentionPin::transaction(txn_manager.clone(), txn_id)),
            txn_manager,
            write_batch: RwLock::new(WriteBatch::new()),
            db_inner,
            isolation_level,
            range_trackers: Mutex::new(Vec::new()),
            read_set: Mutex::new(ReadSet::default()),
            write_tracking: RwLock::new(WriteTracking::default()),
        }
    }

    /// The reads that the commit checks for read-write conflicts. The commit
    /// holds this guard while the transaction manager checks for conflicts.
    pub(crate) fn read_set(&self) -> parking_lot::MutexGuard<'_, ReadSet> {
        self.read_set.lock()
    }

    /// Get a value from the transaction with default read options.
    /// This operation will track the read for conflict detection in SSI mode.
    ///
    /// ## Arguments
    /// - `key`: the key to get
    ///
    /// ## Returns
    /// - `Result<Option<Bytes>, SlateDBError>`: the value if it exists, None otherwise
    pub async fn get<K: AsRef<[u8]> + Send>(&self, key: K) -> Result<Option<Bytes>, crate::Error> {
        self.get_with_options(key, &ReadOptions::default()).await
    }

    /// Get a value from the transaction with custom read options.
    /// This operation will track the read for conflict detection in SSI mode.
    ///
    /// ## Arguments
    /// - `key`: the key to get
    /// - `options`: the read options to use
    ///
    /// ## Returns
    /// - `Result<Option<Bytes>, SlateDBError>`: the value if it exists, None otherwise
    pub async fn get_with_options<K: AsRef<[u8]> + Send>(
        &self,
        key: K,
        options: &ReadOptions,
    ) -> Result<Option<Bytes>, crate::Error> {
        self.get_key_value_with_options(key, options)
            .await
            .map(|kv_opt| kv_opt.map(|kv| kv.value))
    }

    /// Get a key-value pair from the transaction with default read options.
    pub async fn get_key_value<K: AsRef<[u8]> + Send>(
        &self,
        key: K,
    ) -> Result<Option<KeyValue>, crate::Error> {
        self.get_key_value_with_options(key, &ReadOptions::default())
            .await
    }

    /// Get a key-value pair from the transaction with custom read options.
    pub async fn get_key_value_with_options<K: AsRef<[u8]> + Send>(
        &self,
        key: K,
        options: &ReadOptions,
    ) -> Result<Option<KeyValue>, crate::Error> {
        self.db_inner.check_closed()?;

        // Track read key for SSI conflict detection if needed, with the conflict domains of
        // the read options
        if self.isolation_level == IsolationLevel::SerializableSnapshot {
            let mask = options.conflict_mask.unwrap_or(ALL_CONFLICT_DOMAINS);
            if mask != 0 {
                let key_bytes = Bytes::copy_from_slice(key.as_ref());
                self.read_set.lock().mark(key_bytes, mask);
            }
        }

        #[cfg(feature = "range_cache")]
        let sample = match self.range_cache_get(key.as_ref(), options).await {
            crate::range_cache::GetRoute::Served(result) => return result.map_err(Into::into),
            crate::range_cache::GetRoute::Normal(sample) => sample,
        };

        let db_state = self.db_inner.state.read().view();

        // Build the write batch iterator synchronously while holding the read
        // guard, avoiding a clone of the full batch. The iterator materializes
        // only the entries overlapping the read range (a single key for a
        // point get), so this is O(log N) instead of O(N).
        let key_slice = key.as_ref();
        let range = BytesRange::from_slice(key_slice..=key_slice);
        let write_batch_iter = {
            let guard = self.write_batch.read();
            Some(WriteBatchIterator::new(
                &guard,
                range,
                IterationOrder::Ascending,
                u64::MAX,
                None,
                None,
            ))
        };

        let kv = self
            .db_inner
            .reader
            .get_key_value_with_options(
                key,
                options,
                &db_state,
                write_batch_iter,
                Some(self.started_seq),
            )
            .await;
        #[cfg(feature = "range_cache")]
        self.db_inner.range_cache_record(sample);
        kv.map_err(crate::Error::from)
    }

    /// Serves a point read from the write batch or the range cache at `started_seq`.
    /// Falls back for merge operands in the write batch.
    #[cfg(feature = "range_cache")]
    async fn range_cache_get(
        &self,
        key: &[u8],
        options: &ReadOptions,
    ) -> crate::range_cache::GetRoute {
        use crate::batch::WriteOp;
        use crate::range_cache::GetRoute;

        if self.db_inner.range_cache.is_none() || !crate::range_cache::can_serve_get(options) {
            return GetRoute::Normal(None);
        }
        {
            let batch = self.write_batch.read();
            if let Some((batch_key, ops)) = batch.ops.get_key_value(key) {
                return match ops.last() {
                    Some(op @ WriteOp::Put(..)) => {
                        self.db_inner.db_stats.get_requests.increment(1);
                        let entry = op.to_row_entry(batch_key, u64::MAX, None, None);
                        GetRoute::Served(Ok(Some(KeyValue::from(entry))))
                    }
                    Some(WriteOp::Delete) => {
                        self.db_inner.db_stats.get_requests.increment(1);
                        GetRoute::Served(Ok(None))
                    }
                    Some(WriteOp::Merge(..)) | None => GetRoute::Normal(None),
                };
            }
        }
        self.db_inner
            .range_cache_get(key, options, Some(self.started_seq))
            .await
    }

    /// Scan a range of keys using the default scan options.
    /// This operation will track the read range for conflict detection in SSI mode.
    ///
    /// ## Arguments
    /// - `range`: the range of keys to scan
    ///
    /// ## Returns
    /// - `Result<DbIterator, SlateDBError>`: An iterator with the results of the scan
    pub async fn scan<T>(&self, range: T) -> Result<DbIterator, crate::Error>
    where
        T: ByteRangeBounds + Send,
    {
        self.scan_with_options(range, &ScanOptions::default()).await
    }

    /// Scan a range of keys with the provided options.
    /// This operation will track the read range for conflict detection in SSI mode.
    ///
    /// ## Arguments
    /// - `range`: the range of keys to scan
    /// - `options`: the scan options to use
    ///
    /// ## Returns
    /// - `Result<DbIterator, SlateDBError>`: An iterator with the results of the scan
    pub async fn scan_with_options<T>(
        &self,
        range: T,
        options: &ScanOptions,
    ) -> Result<DbIterator, crate::Error>
    where
        T: ByteRangeBounds + Send,
    {
        // TODO: this range conversion logic can be extract to an util
        let start = range.start_bound().map(Bytes::copy_from_slice);
        let end = range.end_bound().map(Bytes::copy_from_slice);
        let range = BytesRange::from((start, end));
        self.scan_inner(range, options, None).await
    }

    /// Scan keys that share the provided prefix, restricted to `subrange`,
    /// using the default scan options.
    /// This operation will track the read range for conflict detection in SSI mode.
    ///
    /// The subrange bounds are key *suffixes* interpreted relative to the
    /// prefix: a bound `s` selects the full key `prefix ++ s`. Pass `..` to
    /// scan the prefix's entire keyspace.
    ///
    /// ## Arguments
    /// - `prefix`: the key prefix to scan
    /// - `subrange`: the range of key suffixes (relative to `prefix`) to
    ///   scan; `..` scans all keys with the prefix
    ///
    /// ## Returns
    /// - `Result<DbIterator, SlateDBError>`: An iterator with the results of the scan
    pub async fn scan_prefix<P, T>(
        &self,
        prefix: P,
        subrange: T,
    ) -> Result<DbIterator, crate::Error>
    where
        P: AsRef<[u8]> + Send,
        T: ByteRangeBounds + Send,
    {
        self.scan_prefix_with_options(prefix, subrange, &ScanOptions::default())
            .await
    }

    /// Scan keys that share the provided prefix, restricted to `subrange`,
    /// with custom options. See [`Self::scan_prefix`] for the subrange
    /// semantics.
    /// This operation will track the read range for conflict detection in SSI mode.
    ///
    /// ## Arguments
    /// - `prefix`: the key prefix to scan
    /// - `subrange`: the range of key suffixes (relative to `prefix`) to
    ///   scan; `..` scans all keys with the prefix
    /// - `options`: the scan options to use
    ///
    /// ## Returns
    /// - `Result<DbIterator, SlateDBError>`: An iterator with the results of the scan
    pub async fn scan_prefix_with_options<P, T>(
        &self,
        prefix: P,
        subrange: T,
        options: &ScanOptions,
    ) -> Result<DbIterator, crate::Error>
    where
        P: AsRef<[u8]> + Send,
        T: ByteRangeBounds + Send,
    {
        let prefix = Bytes::copy_from_slice(prefix.as_ref());
        let range = BytesRange::from_prefix_and_subrange(prefix.as_ref(), subrange);
        self.scan_inner(range, options, Some(prefix)).await
    }

    async fn scan_inner(
        &self,
        range: BytesRange,
        options: &ScanOptions,
        prefix: Option<Bytes>,
    ) -> Result<DbIterator, crate::Error> {
        // Under SSI, register the *requested* scan range with the transaction
        // so that any concurrent write inside it is detected as an
        // rw-anti-dependency at commit time — including writes to portions of
        // the range that the iterator never yielded (empty scans, partial
        // scans, scans whose tombstones were skipped). See
        // `DbIteratorRangeTracker` for the rationale.
        if self.isolation_level == IsolationLevel::SerializableSnapshot {
            let mask = options.conflict_mask.unwrap_or(ALL_CONFLICT_DOMAINS);
            if mask != 0 {
                let tracker = DbIteratorRangeTracker::new(range.clone());
                self.range_trackers.lock().push((tracker, mask));
            }
        }

        self.db_inner.check_closed()?;

        // Serve from the range cache when the transaction has no pending writes in `range`.
        #[cfg(feature = "range_cache")]
        let (range, sample) = {
            let batch_overlaps = self.db_inner.range_cache.is_some() && {
                let guard = self.write_batch.read();
                guard
                    .ops
                    .range::<Bytes, _>((
                        std::ops::RangeBounds::start_bound(&range),
                        std::ops::RangeBounds::end_bound(&range),
                    ))
                    .next()
                    .is_some()
            };
            if batch_overlaps {
                (range, None)
            } else {
                match self
                    .db_inner
                    .range_cache_scan(range, options, prefix.as_ref(), Some(self.started_seq))
                    .await
                {
                    crate::range_cache::ScanRoute::Served(result) => {
                        return result.map(|iter| self.retaining(iter)).map_err(Into::into)
                    }
                    crate::range_cache::ScanRoute::Normal(range, sample) => (range, sample),
                }
            }
        };

        let db_state = self.db_inner.state.read().view();

        // Build the write batch iterator synchronously while holding the read
        // guard, avoiding a clone of the full batch. The iterator materializes
        // only the entries in the scan range.
        let write_batch_iter = {
            let guard = self.write_batch.read();
            Some(WriteBatchIterator::new(
                &guard,
                range.clone(),
                options.order,
                u64::MAX,
                None,
                None,
            ))
        };

        let result = self
            .db_inner
            .reader
            .scan_with_options(
                range,
                options,
                ScanContext {
                    db_state: &db_state,
                    write_batch_iter,
                    max_seq: Some(self.started_seq),
                    prefix,
                },
            )
            .await;
        #[cfg(feature = "range_cache")]
        self.db_inner.range_cache_record(sample);
        result.map(|iter| self.retaining(iter)).map_err(Into::into)
    }

    /// Attaches the transaction's retention pin to `iter`.
    fn retaining(&self, iter: DbIterator) -> DbIterator {
        match &self.retention {
            Some(pin) => iter.retaining(pin.clone()),
            None => iter,
        }
    }

    /// Returns true if an open scan iterator still holds this transaction's retention pin.
    pub(crate) fn scans_hold_retention(&self) -> bool {
        self.retention
            .as_ref()
            .is_some_and(|pin| Arc::strong_count(pin) > 1)
    }

    /// Put a key-value pair into the transaction.
    /// The write will be buffered in the transaction's write batch until commit.
    ///
    /// ## Arguments
    /// - `key`: the key to write
    /// - `value`: the value to write
    ///
    /// ## Errors
    /// - It's not really possible to have error here, since the write operation is
    ///   buffered in the write batch.
    pub fn put<K, V>(&self, key: K, value: V) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        V: AsRef<[u8]>,
    {
        self.put_with_options(key, value, &PutOptions::default())
    }

    /// Put a key-value pair into the transaction with custom options.
    /// The write will be buffered in the transaction's write batch until commit.
    ///
    /// ## Arguments
    /// - `key`: the key to write
    /// - `value`: the value to write
    /// - `options`: the put options to use
    ///
    /// ## Errors
    /// - It's not really possible to have error here, since the write operation is
    ///   buffered in the write batch.
    pub fn put_with_options<K, V>(
        &self,
        key: K,
        value: V,
        options: &PutOptions,
    ) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        V: AsRef<[u8]>,
    {
        self.write_batch
            .write()
            .put_with_options(key, value, options);
        Ok(())
    }

    /// Put a key-value pair into the transaction using owned [`Bytes`].
    /// This avoids the buffer copies that [`Self::put`] performs.
    /// The write stays buffered in the transaction's write batch until commit.
    ///
    /// # Panics
    /// - If the key is empty.
    /// - If the key or value size is larger than `u32::MAX`.
    pub fn put_bytes(&self, key: Bytes, value: Bytes) -> Result<(), crate::Error> {
        self.put_bytes_with_options(key, value, &PutOptions::default())
    }

    /// Put a key-value pair into the transaction using owned [`Bytes`] with custom options.
    /// See [`Self::put_bytes`] for the buffer ownership behavior.
    /// The write stays buffered in the transaction's write batch until commit.
    ///
    /// # Panics
    /// - If the key is empty.
    /// - If the key or value size is larger than `u32::MAX`.
    pub fn put_bytes_with_options(
        &self,
        key: Bytes,
        value: Bytes,
        options: &PutOptions,
    ) -> Result<(), crate::Error> {
        self.write_batch
            .write()
            .put_bytes_with_options(key, value, options);
        Ok(())
    }

    /// Mark keys as read for conflict detection.
    ///
    /// This method explicitly tracks read operations for conflict detection. When keys are
    /// marked as read, the transaction will detect conflicts if another transaction modifies
    /// any of those keys after this transaction started, regardless of the isolation level.
    ///
    /// This allows for selective read-write conflict detection even in Snapshot Isolation mode,
    /// where reads are not automatically tracked (unlike `get()` which only tracks reads in SSI
    /// mode).
    ///
    /// ## Arguments
    /// - `keys`: an iterator of keys to mark as read
    ///
    /// ## Examples
    /// ```rust
    /// # async fn example() -> Result<(), slatedb::Error> {
    /// # use std::sync::Arc;
    /// # use slatedb::object_store::memory::InMemory;
    /// use slatedb::{Db, IsolationLevel};
    ///
    /// # let object_store = Arc::new(InMemory::new());
    /// # let db = Db::open("test_path", object_store).await?;
    /// let txn = db.begin(IsolationLevel::Snapshot)?;
    /// txn.mark_read([b"key1", b"key2", b"key3"])?;
    /// # Ok(())
    /// # }
    /// ```
    pub fn mark_read<K, I>(&self, keys: I) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        I: IntoIterator<Item = K>,
    {
        // Always track reads when explicitly marked, regardless of isolation level.
        // The current conflict checking logic always checks the read_keys set
        // even in SI mode. The only difference between SI and SSI is whether
        // the read keys are tracked in the read set or not.

        self.mark_read_masked(keys, ALL_CONFLICT_DOMAINS)
    }

    /// Mark keys as read in some of their conflict domains only.
    ///
    /// This method behaves the same as [`DbTransaction::mark_read`], but the read of each key
    /// used only the conflict domains whose bits are set in `mask`: a write of the key by
    /// another transaction conflicts with it only if that write changed one of those domains
    /// (see [`DbTransaction::set_write_mask`]). A write with no mask changes every domain, so
    /// it conflicts with any marked read. SlateDB does not interpret the bits. A key marked
    /// more than once is read in the union of the masks. A mask of 0 marks nothing.
    ///
    /// ## Arguments
    /// - `keys`: an iterator of keys to mark as read
    /// - `mask`: the conflict domains that the reads of the keys used
    ///
    /// ## Examples
    /// ```rust
    /// # async fn example() -> Result<(), slatedb::Error> {
    /// # use std::sync::Arc;
    /// # use slatedb::object_store::memory::InMemory;
    /// use slatedb::{Db, IsolationLevel};
    ///
    /// # let object_store = Arc::new(InMemory::new());
    /// # let db = Db::open("test_path", object_store).await?;
    /// let txn = db.begin(IsolationLevel::Snapshot)?;
    /// // The read used the domains of bits 0 and 2 of "row1".
    /// txn.mark_read_masked([b"row1"], 0b101)?;
    /// # Ok(())
    /// # }
    /// ```
    pub fn mark_read_masked<K, I>(&self, keys: I, mask: u64) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        I: IntoIterator<Item = K>,
    {
        // Always track reads when explicitly marked, regardless of isolation level, as
        // `mark_read` does.
        let mut read_set = self.read_set.lock();
        for key in keys {
            read_set.mark(Bytes::copy_from_slice(key.as_ref()), mask);
        }
        Ok(())
    }

    /// Mark a range of keys as read in some of their conflict domains, without reading it.
    ///
    /// The commit's conflict check treats `range` as it treats the range of a Serializable scan
    /// with the conflict mask `mask` (see [`crate::config::ScanOptions::conflict_mask`]) that
    /// ran to its end: a write of any key inside the range, existing or not, committed by
    /// another transaction after this one started, conflicts with it if that write changed one
    /// of the domains whose bits are set in `mask` (see [`DbTransaction::set_write_mask`]).
    /// SlateDB reads nothing and does not interpret the bits. Like
    /// [`DbTransaction::mark_read_masked`], and unlike a scan, which registers its range only in
    /// a Serializable transaction, it counts whenever it is called, regardless of the isolation
    /// level. A mask of 0 marks nothing. Neither does an empty range (such as `b"b"..b"a"` or
    /// `b"a"..b"a"`), which holds no key that a write could change; a scan of an empty range
    /// panics instead.
    ///
    /// ## Arguments
    /// - `range`: the range of keys to mark as read, in any form that [`DbTransaction::scan`]
    ///   takes
    /// - `mask`: the conflict domains that the read of the range used
    ///
    /// ## Examples
    /// ```rust
    /// # async fn example() -> Result<(), slatedb::Error> {
    /// # use std::sync::Arc;
    /// # use slatedb::object_store::memory::InMemory;
    /// use slatedb::{Db, IsolationLevel};
    ///
    /// # let object_store = Arc::new(InMemory::new());
    /// # let db = Db::open("test_path", object_store).await?;
    /// let txn = db.begin(IsolationLevel::Snapshot)?;
    /// // The read of the keys from "row1" up to "row5", excluded, used the domain of bit 0.
    /// txn.mark_read_range(b"row1"..b"row5", 0b1)?;
    /// // The read of every key from "user/" on used every domain.
    /// txn.mark_read_range(b"user/".as_slice().., u64::MAX)?;
    /// # Ok(())
    /// # }
    /// ```
    pub fn mark_read_range<T>(&self, range: T, mask: u64) -> Result<(), crate::Error>
    where
        T: ByteRangeBounds,
    {
        if mask == 0 {
            return Ok(());
        }
        let start = range.start_bound().map(Bytes::copy_from_slice);
        let end = range.end_bound().map(Bytes::copy_from_slice);
        if let Some(range) = BytesRange::try_new(start, end) {
            self.read_set.lock().ranges.push((range, mask));
        }
        Ok(())
    }

    /// Set the conflict domains that this transaction's write of a key changes.
    ///
    /// By default a write of a key changes every conflict domain of the key, so any read of the
    /// key by a concurrent transaction conflicts with it. With a mask, a read of the key by
    /// another transaction conflicts with this write only if the read used one of the domains
    /// whose bits are set in `mask` (see [`DbTransaction::mark_read_masked`] and
    /// [`crate::config::ReadOptions::conflict_mask`]). The caller promises that the mask covers
    /// everything that the transaction's write changes relative to the newest committed value
    /// of the key. SlateDB does not interpret the bits.
    ///
    /// The mask applies to the transaction's writes of the key whenever it is set, before or
    /// after the writes. Masks set more than once for a key join: the write changes the union.
    /// A mask has no effect on a key that the transaction does not write, and none on the
    /// write-write conflict check, which compares keys whatever their masks, as the write still
    /// replaces the whole value. A key passed to [`DbTransaction::unmark_write`] leaves every
    /// check, with or without a mask.
    ///
    /// ## Arguments
    /// - `key`: the key that the transaction writes
    /// - `mask`: the conflict domains that the write changes
    ///
    /// ## Examples
    /// ```rust
    /// # async fn example() -> Result<(), slatedb::Error> {
    /// # use std::sync::Arc;
    /// # use slatedb::object_store::memory::InMemory;
    /// use slatedb::{Db, IsolationLevel};
    ///
    /// # let object_store = Arc::new(InMemory::new());
    /// # let db = Db::open("test_path", object_store).await?;
    /// let txn = db.begin(IsolationLevel::SerializableSnapshot)?;
    /// txn.put(b"row1", b"new value")?;
    /// // The new value differs from the committed one only in the domain of bit 1.
    /// txn.set_write_mask(b"row1", 0b10)?;
    /// txn.commit().await?;
    /// # Ok(())
    /// # }
    /// ```
    pub fn set_write_mask<K: AsRef<[u8]>>(&self, key: K, mask: u64) -> Result<(), crate::Error> {
        let mut tracking = self.write_tracking.write();
        *tracking
            .masks
            .entry(Bytes::copy_from_slice(key.as_ref()))
            .or_insert(0) |= mask;
        Ok(())
    }

    /// Validate the write of a key only against commits made after sequence number `seq`.
    ///
    /// By default the write-write check of a written key conflicts with every commit of the
    /// key made after the transaction started. After this call it conflicts only with the
    /// commits of the key made after both the start and `seq`. The caller promises that the
    /// value it writes for the key was computed from the version of the key committed at
    /// `seq` (its `KeyValue::seq`), and that this version was the newest committed one when
    /// the caller read it, after the transaction began, as [`crate::Db::get_key_value`] with
    /// default read options reads it. A commit of the key that this read did not see is newer than `seq` and still
    /// conflicts. A `seq` below the transaction's start changes nothing. A key given more than
    /// once keeps the smallest `seq`. Read-write checks, the checks of other keys, and keys
    /// that the transaction does not write are unaffected; a key passed to
    /// [`DbTransaction::unmark_write`] leaves every check anyway.
    ///
    /// ## Arguments
    /// - `key`: the key that the transaction writes
    /// - `seq`: the sequence number of the version that the written value was computed from
    pub fn validate_write_since<K: AsRef<[u8]>>(
        &self,
        key: K,
        seq: u64,
    ) -> Result<(), crate::Error> {
        let mut tracking = self.write_tracking.write();
        let had = tracking
            .since
            .entry(Bytes::copy_from_slice(key.as_ref()))
            .or_insert(seq);
        *had = (*had).min(seq);
        Ok(())
    }

    /// Mark written keys as untracked for conflict detection.
    ///
    /// Keys marked with this method are still written atomically with the rest of the
    /// transaction, but are excluded from transaction conflict detection on commit for
    /// both this transaction and other transactions.
    ///
    /// This means:
    /// - If another transaction reads a key written with an `unmark_write` by this transaction, that key
    ///   will not cause a read-write conflict.
    /// - If another transaction writes a key written with an `unmark_write` by this transaction, that key
    ///   will not cause a write-write conflict.
    ///
    /// You may call `unmark_write` either before or after writing a key in the transaction.
    /// Once a key is unmarked, it cannot be marked again within the same transaction and
    /// remains unmarked for the duration of this transaction, even if `put`, `merge`, or
    /// `delete` is called on the same key later in the transaction.
    ///
    /// ## Arguments
    /// - `keys`: an iterator of keys to exclude from write conflict tracking
    ///
    /// ## Examples
    /// ```rust
    /// # async fn example() -> Result<(), slatedb::Error> {
    /// # use std::sync::Arc;
    /// # use slatedb::object_store::memory::InMemory;
    /// use slatedb::{Db, IsolationLevel};
    ///
    /// # let object_store = Arc::new(InMemory::new());
    /// # let db = Db::open("test_path", object_store).await?;
    /// let txn = db.begin(IsolationLevel::Snapshot)?;
    /// txn.put(b"counter", b"1")?;
    /// txn.unmark_write([b"counter"])?;
    /// txn.put(b"counter", b"2")?;
    /// txn.commit().await?;
    /// # Ok(())
    /// # }
    /// ```
    pub fn unmark_write<K, I>(&self, keys: I) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        I: IntoIterator<Item = K>,
    {
        let mut tracking = self.write_tracking.write();
        let untracked_keys = keys.into_iter().map(|k| Bytes::copy_from_slice(k.as_ref()));
        tracking.untracked.extend(untracked_keys);
        Ok(())
    }

    /// Merge a key-value pair into the transaction.
    ///
    /// ## Errors
    /// - `Error`: if no merge operator is configured for the database.
    pub fn merge<K, V>(&self, key: K, value: V) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        V: AsRef<[u8]>,
    {
        self.merge_with_options(key, value, &MergeOptions::default())
    }

    /// Merge a key-value pair into the transaction with custom options.
    ///
    /// ## Errors
    /// - `Error`: if no merge operator is configured for the database.
    pub fn merge_with_options<K, V>(
        &self,
        key: K,
        value: V,
        options: &MergeOptions,
    ) -> Result<(), crate::Error>
    where
        K: AsRef<[u8]>,
        V: AsRef<[u8]>,
    {
        if self.db_inner.flush_merge_operator.is_none() {
            return Err(SlateDBError::MergeOperatorMissing.into());
        }

        self.write_batch
            .write()
            .merge_with_options(key, value, options);
        Ok(())
    }

    /// Delete a key from the transaction.
    /// The delete will be buffered in the transaction's write batch until commit.
    ///
    /// ## Arguments
    /// - `key`: the key to delete
    ///
    /// ## Errors
    /// - It's not really possible to have error here, since the delete operation is
    ///   buffered in the write batch.
    pub fn delete<K: AsRef<[u8]>>(&self, key: K) -> Result<(), crate::Error> {
        self.write_batch.write().delete(key);
        Ok(())
    }

    /// Commit the transaction by applying all buffered operations to the database.
    ///
    /// This method finalizes the transaction by writing all pending puts,
    /// deletes, and other operations from the write batch to the in-memory WAL
    /// and MemTable. The actual conflict detection (including read-write and
    /// write-write conflicts) is deferred to the task that processes the
    /// WriteBatch, which ensures the atomicity of transactions.
    ///
    /// A successful commit does not wait for durability in object storage.
    /// Call [`WriteHandle::await_durable`] on the returned handle when the
    /// result is `Some`, or call [`crate::Db::flush`] to flush all pending
    /// writes.
    ///
    /// If the transaction's write batch is empty, this operation is a no-op and returns `Ok(())`
    /// immediately without any database interaction. Since it's impossible to have read-write
    /// conflict, neither write-write conflict for an empty write batch.
    ///
    /// ## Returns
    /// - `Ok(Some(WriteHandle))` if the commit is successful and there are writes in the batch.
    /// - `Ok(None)` if the commit is successful but the write batch is empty (no-op).
    ///
    /// ## Errors
    /// - Returns `Error` if the commit operation fails, which could be due to:
    ///   - Database I/O errors
    ///   - Concurrency conflicts detected during WriteBatch processing
    pub async fn commit(self) -> Result<Option<WriteHandle>, crate::Error> {
        self.commit_with_options(&WriteOptions::default()).await
    }

    /// Commit the transaction with custom write options.
    ///
    /// This method behaves the same as [`DbTransaction::commit`], but allows callers
    /// to specify custom [`WriteOptions`].
    ///
    /// A successful commit does not wait for durability in object storage.
    /// Call [`WriteHandle::await_durable`] on the returned handle when the
    /// result is `Some`, or call [`crate::Db::flush`] to flush all pending
    /// writes.
    ///
    /// ## Arguments
    /// - `options`: the write options to use for the commit
    ///
    /// ## Returns
    /// - `Ok(Some(WriteHandle))` if the commit is successful and there are writes in the batch.
    /// - `Ok(None)` if the commit is successful but the write batch is empty (no-op).
    ///
    /// ## Errors
    /// - Returns `Error` if the commit operation fails, which could be due to:
    ///   - Database I/O errors
    ///   - Concurrency conflicts detected during WriteBatch processing
    pub async fn commit_with_options(
        self,
        options: &WriteOptions,
    ) -> Result<Option<WriteHandle>, crate::Error> {
        // Take the write_batch for submission to the database.
        let write_batch = self.write_batch.read().clone();

        // Materialize the SSI read-range dependencies the transaction
        // accumulated during scans. Each tracker carries the requested scan
        // range; the conflict check in `TransactionManager` will then catch
        // any committed write whose key falls inside it.
        // The ranges are taken now: a scan that goes on after this call does not
        // add to them. The ranges of `mark_read_range` are in the read set already,
        // at every isolation level, and both checks below read the whole read set.
        if self.isolation_level == IsolationLevel::SerializableSnapshot {
            let ranges: Vec<(BytesRange, u64)> = self
                .range_trackers
                .lock()
                .iter()
                .map(|(tracker, mask)| (tracker.get_range(), *mask))
                .collect();
            self.read_set.lock().ranges.extend(ranges);
        }

        // If the WriteBatch is empty, it's a no-op or read-only batch.
        if write_batch.is_empty() {
            // Check for read conflicts before returning Ok(None).
            if self
                .txn_manager
                .check_has_conflict_with_reads(&self.txn_id, &self.read_set())
            {
                return Err(SlateDBError::TransactionConflict.into());
            }
            return Ok(None);
        }

        // Track only write keys that were not explicitly unmarked, each with the conflict
        // domains that its write changes: every domain unless a mask was set.
        let (tracked_write_keys, since): (WriteKeys, _) = {
            let tracking = self.write_tracking.read();
            let keys = write_batch
                .keys()
                .into_iter()
                .filter(|key| !tracking.untracked.contains(key))
                .map(|key| {
                    let mark = tracking
                        .masks
                        .get(&key)
                        .map_or(WriteMark::ALL, |&mask| WriteMark { mask });
                    (key, mark)
                })
                .collect();
            (keys, tracking.since.clone())
        };
        self.txn_manager
            .track_writes(&self.txn_id, tracked_write_keys, since);

        // Submit the WriteBatch to the database for processing. The batch is sent to a
        // dedicated background task (in batch_write.rs) that processes all WriteBatches
        // sequentially, ensuring no concurrent writes. Both conflict checking & persisting
        // are handled there.
        let db_inner = Arc::clone(&self.db_inner);
        db_inner
            .write_with_options(write_batch, options, Some(self))
            .await
            .map(Some)
            .map_err(Into::into)
    }

    /// Rollback the transaction by discarding all buffered operations.
    /// This is automatically called when the transaction is dropped.
    pub fn rollback(self) {
        // do nothing, trigger the Drop of the transaction
    }

    /// Get the sequence number this transaction was started at. This is equivalent to
    /// the snapshot sequence number for this transaction, which determines data visibility
    /// for reads in this transaction.
    pub fn seqnum(&self) -> u64 {
        self.started_seq
    }

    /// Get the transaction ID. This is a unique identifier for this transaction, generated
    /// by the transaction manager.
    pub fn id(&self) -> Uuid {
        self.txn_id
    }
}

